#!/usr/bin/env python3
"""Write port/src/tables.h: the lookup tables the original engine builds at start-up.

The engine (FUN_0000e920) fills a 360-entry sine and cosine table and 100-entry easing
tables. The easing tables use only double additions and multiplications, so they are
reproduced exactly. sinf/cosf come from the phone's libm, which is not in the executable;
correctly rounded single-precision values are used here.
"""
import math
import struct
from pathlib import Path


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def table(name, values):
    rows = []
    for i in range(0, len(values), 5):
        rows.append('    ' + ' '.join('%sf,' % float.hex(f32(v)) for v in values[i:i + 5]))
    return 'static const float %s[%d] = {\n%s\n};\n' % (name, len(values), '\n'.join(rows))


angles = [f32((i * 3.1415926) / 180.0) for i in range(360)]
x = [i / 100.0 for i in range(100)]
out = ['/* Generated by tools/make_tables.py; do not edit. */\n#ifndef FB_TABLES_H\n#define FB_TABLES_H\n',
       table('kSin', [math.sin(a) for a in angles]),
       table('kCos', [math.cos(a) for a in angles]),
       '/* easing 5: (x-1)^3 + 1; easing 11: (x-1)^5 + 1, at x = i/100 */\n',
       table('kEaseCubicOut', [(v - 1.0) * (v - 1.0) * (v - 1.0) + 1.0 for v in x]),
       table('kEaseQuintOut', [(v - 1.0) * (v - 1.0) * ((v - 1.0) * (v - 1.0) * (v - 1.0)) + 1.0 for v in x]),
       '#endif\n']
Path(__file__).resolve().parents[1].joinpath('port/src/tables.h').write_text(''.join(out))
